   fun a(): Int

   @JvmName(name = "b")
   fun b(): He

   @JvmName(name = "c")
   fun c(): T

   @JvmName(name = "a")
   fun a(var1: T)

   @JvmName(name = "d")
   fun d(): Hg

   @JvmName(name = "a")
   fun a(var1: Hg)

   @JvmName(name = "e")
   fun e(): Hb

   @JvmName(name = "a")
   fun a(var1: Hb)

   @JvmName(name = "f")
   fun f(): Boolean

   @JvmName(name = "a")
   fun a(var1: Boolean)

   @JvmName(name = "g")
   fun g(): Double

   @JvmName(name = "a")
   fun a(var1: Double)

   @JvmName(name = "h")
   fun h(): Double

   @JvmName(name = "b")
   fun b(var1: Double)

   @JvmName(name = "i")
   fun i(): Double

   @JvmName(name = "c")
   fun c(var1: Double)

   @JvmName(name = "j")
   fun j(): Double

   @JvmName(name = "d")
   fun d(var1: Double)

   @JvmName(name = "k")
   fun k(): Vector3dc

   @JvmName(name = "a")
   fun a(var1: Vector3dc)

   @JvmName(name = "l")
   fun l(): Double

   @JvmName(name = "e")
   fun e(var1: Double)

   @JvmName(name = "m")
   fun m(): Boolean

   @JvmName(name = "b")
   fun b(var1: Boolean)

   @JvmName(name = "n")
   fun n(): Int

   @JvmName(name = "a")
   fun a(var1: Int)

   @JvmName(name = "o")
   fun o(): Hf

   @JvmName(name = "a")
   fun a(var1: Hf)

   fun b(var1: Vector3dc)

   fun c(var1: Vector3dc)

   fun d(var1: Vector3dc)

   fun e(var1: Vector3dc)

   fun a(var1: Vector3dc, var2: Vector3dc)

   fun p(): Boolean

   fun a(var1: AABBd): Boolean

   fun q()

   fun r(): Boolean

   fun s(): Double
}
